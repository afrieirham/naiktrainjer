#!/usr/bin/env node
/**
 * Sync the Place directory from PocketBase: every Place and its Connections.
 *
 * PocketBase (`POCKETBASE_URL`, default `http://pocketbase.pi`) holds the live
 * Place records; `data/places.ts` is the committed snapshot the app reads. This
 * script copies the first into the second, whole. It is run by hand and is never
 * part of `npm run build`, so a deploy cannot depend on PocketBase being
 * reachable.
 *
 * The snapshot is a TypeScript module rather than JSON on purpose: Cloudflare's
 * Pages Functions bundler cannot parse JSON import attributes (`with { type:
 * "json" }`), and Node refuses a JSON import without one. A generated module
 * loads unchanged in Vite, in Node, and in the Functions bundler.
 *
 * PocketBase stores a Connection's Station as a relation id; the snapshot
 * carries the network code so the app never sees an id. A Connection's own
 * `sort` orders a Place's Connections (the first headlines the Place page), so
 * the records are fetched ordered by `sort,id`; Places are sorted by slug. Both
 * keep the snapshot stable against fetch order.
 *
 * Usage: `npm run export-places`
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const DATA_PATH = resolve(root, 'data/places.ts');

const BASE_URL = process.env.POCKETBASE_URL ?? 'http://pocketbase.pi';

async function fetchAll(collection, query = '') {
  const items = [];
  for (let page = 1; ; page++) {
    const url =
      `${BASE_URL}/api/collections/${collection}/records?perPage=200&page=${page}` +
      (query ? `&${query}` : '');
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${res.status} ${res.statusText} from ${url}`);
    const body = await res.json();
    items.push(...body.items);
    if (page >= body.totalPages) return items;
  }
}

export function buildPlaces(placeRecords, connectionRecords, stationRecords) {
  const stationCodeById = new Map(stationRecords.map((s) => [s.id, s.code]));

  const codeOf = (id) => {
    const code = stationCodeById.get(id);
    if (!code) {
      throw new Error(`A Connection links to Station ${id}, which is not in train_stations`);
    }
    return code;
  };

  const connectionsByPlaceId = new Map();
  for (const connection of connectionRecords) {
    const list = connectionsByPlaceId.get(connection.place) ?? [];
    list.push(connection);
    connectionsByPlaceId.set(connection.place, list);
  }

  return placeRecords
    .map((place) => {
      // Preserve the record order (the caller fetches by `sort,id`).
      const connections = (connectionsByPlaceId.get(place.id) ?? []).map(
        (connection) => {
          const station = codeOf(connection.station);
          return { station, ...(connection.embed ? { embed: connection.embed } : {}) };
        },
      );

      return {
        slug: place.slug,
        name: place.name,
        kind: place.kind,
        type: place.type,
        map: place.map,
        source: place.source,
        connections,
        ...(place.contributor_name
          ? {
              contributor: {
                name: place.contributor_name,
                href: place.contributor_href || null,
              },
            }
          : {}),
      };
    })
    .sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
}

async function main() {
  const [placeRecords, connectionRecords, stationRecords] = await Promise.all([
    fetchAll('naiktrainjer_places'),
    fetchAll('naiktrainjer_connections', 'sort=sort,id'),
    fetchAll('train_stations'),
  ]);
  console.log(
    `Read ${placeRecords.length} Places, ${connectionRecords.length} Connections and ` +
      `${stationRecords.length} Stations from ${BASE_URL}`,
  );

  const places = buildPlaces(placeRecords, connectionRecords, stationRecords);

  const next =
    `// Generated by scripts/export-places.mjs from PocketBase.\n` +
    `// Do not edit by hand; run \`npm run export-places\` to refresh it.\n\n` +
    `export type PlaceConnection = { station: string; embed?: string };\n` +
    `export type Place = {\n` +
    `  slug: string;\n` +
    `  name: string;\n` +
    `  kind: "building" | "area";\n` +
    `  type: string;\n` +
    `  map: string;\n` +
    `  connections: PlaceConnection[];\n` +
    `  source: string;\n` +
    `  contributor?: { name: string; href: string | null };\n` +
    `};\n\n` +
    `export const places: Place[] = ${JSON.stringify(places, null, 2)};\n\n` +
    `export default { places };\n`;
  writeFileSync(DATA_PATH, next);

  const total = places.reduce((n, p) => n + p.connections.length, 0);
  console.log(`Wrote ${places.length} Places and ${total} Connections to data/places.ts`);
}

/**
 * Run only when invoked as a script. Importing this module — as the tests do
 * for `buildPlaces` — must not reach PocketBase or rewrite the snapshot.
 */
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main().catch((e) => {
    console.error(`Export failed: ${e.message}`);
    process.exit(1);
  });
}
